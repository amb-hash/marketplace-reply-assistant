"""Анонимизация текста перед отправкой в LLM.

Простые regex-паттерны: телефоны, e-mail, номера заказов/карт, адреса.
Никакого ML и NER — только явные паттерны. Если что-то не распозналось,
но похоже на личные данные — текст всё равно пройдёт, финальный контроль
за оператором. Это фильтр от очевидного, а не юридическая гарантия.
"""

from __future__ import annotations

import re

# Порядок важен: сначала специфичные, потом общие.
_PATTERNS: list[tuple[str, str]] = [
    # E-mail
    (r"[\w.+-]+@[\w-]+\.[\w.-]+", "[email]"),
    # URL (могут содержать персональные данные)
    (r"https?://\S+", "[ссылка]"),
    # Банковские карты: 16 цифр (с пробелами/дефисами)
    (r"\d{4}[\s\-]?\d{4}[\s\-]?\d{4}[\s\-]?\d{4}", "[карта]"),
    # Номера заказов: «заказ №123456», «номер заказа 123456»
    (r"(?:заказ[а-яё]*|номер\s+заказа)[^\d]{0,5}\d{4,}", "[заказ]"),
    # Телефоны: +7..., 8... (10-11 цифр, с разделителями)
    (r"(?:\+?\d{1,3}[\s\-]?)?\(?\d{2,4}\)?[\s\-]?\d{2,3}[\s\-]?\d{2,3}[\s\-]?\d{2,3}", "[телефон]"),
    # Длинные номера (трек-номеры, штрихкоды): 10+ цифр подряд
    (r"\d{10,}", "[номер]"),
    # Адреса: ключевые слова с границами слов
    (r"\b(?:ул\.|улица|проспект|пр-т|пер\.|переулок|бул\.|бульвар|ш\.|шоссе)\s+\S+", "[адрес]"),
    (r"\b(?:д|дом)\.?\s*\d+,\s*(?:кв|квартира)\.?\s*\d+", "[адрес]"),
    (r"\b(?:корп|корпус)\.?\s*\d+", "[корпус]"),
    (r"\b(?:г|город)\.\s*[А-Яа-яЁё]{2,}", "[город]"),
]


def anonymize(text: str) -> tuple[str, int]:
    """Заменяет персональные данные на плейсхолдеры.

    Возвращает (очищенный_текст, количество_замен).
    Если замен не было — текст возвращается как есть.
    """
    if not text:
        return text, 0
    result = text
    total = 0
    for pattern, placeholder in _PATTERNS:
        result, n = re.subn(pattern, placeholder, result)
        total += n
    return result, total
